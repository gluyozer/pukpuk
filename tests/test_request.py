class ParseRequestTest(unittest.TestCase):
    def test_kind_theme_and_count(self):
        r = parse_request("придумай 3 идеи для игры про космос")
        self.assertEqual((r.kind, r.themes, r.count), ("игра", ["космос"], 3))

    def test_two_themes_make_a_mashup(self):
        r = parse_request("хочу игру про море и роботов")
        self.assertEqual((r.kind, r.themes), ("игра", ["море", "роботы"]))

    def test_inflected_forms(self):
        self.assertEqual(parse_request("приложение про кошек").themes, ["животные"])
        self.assertEqual(parse_request("бот про музыку").themes, ["музыка"])
        self.assertEqual(parse_request("нейросеть про динозавров").kind, "ии")
        self.assertEqual(parse_request("сайт про ёжиков в лесу").themes, ["лес"])
        self.assertEqual(parse_request("сделай бота про еду").kind, "бот")

    def test_natural_word_forms_find_their_theme(self):
        self.assertEqual(set(THEME_WORD_FORMS), set(THEMES), "в таблице должны быть все темы")
        for theme, words in THEME_WORD_FORMS.items():
            for word in words.split():
                normalized = word.replace("ё", "е")
                # слово не должно подходить сразу двум темам — иначе тема выбиралась бы случайно по порядку
                self.assertEqual(match_themes(normalized), [theme], f"{theme}: слово «{word}»")
                self.assertEqual(parse_request(f"игра про {word}").themes, [theme], f"{theme}: слово «{word}»")

    def test_short_words_do_not_match_by_accident(self):
        # «который» начинается на «кот», «супер» — на «суп», «рок» не должен цепляться к «роковой»
        r = parse_request("игра, который супер")
        self.assertEqual(r.themes, [])
        # «лестница» — не про лес, «деревня» — не про деревья
        self.assertEqual(match_themes("лестница"), [])
        self.assertEqual(match_themes("деревня"), ["ферма"])

    def test_unknown_words_are_reported(self):
        r = parse_request("придумай игру про оригами")
        self.assertEqual((r.kind, r.themes, r.unknown), ("игра", [], ["оригами"]))

    def test_count_is_capped_and_words_work(self):
        self.assertEqual(parse_request("100 игр").count, 1)
        self.assertEqual(parse_request("пять идей").count, 5)
        self.assertEqual(parse_request("2 идеи").count, 2)

    def test_forced_kind_from_command(self):
        r = parse_request("космос", kind="сайт")
        self.assertEqual((r.kind, r.themes), ("сайт", ["космос"]))

    def test_empty(self):
        r = parse_request("")
        self.assertEqual((r.kind, r.themes, r.count, r.unknown), (None, [], 1, []))


if __name__ == "__main__":
    unittest.main()
